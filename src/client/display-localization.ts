export function localizeDisplayProject(project: CanonicalProject, locale: Locale): CanonicalProject {
  if (project.manifest.id !== "project-ai-landscape") return project;
  const dictionary = dictionaries[locale];
  return {
    ...project,
    topics: project.topics.map((topic) => ({ ...topic, ...dictionary.topics[topic.id] })),
    keyIssues: project.keyIssues.map((issue) => ({ ...issue, ...dictionary.keyIssues[issue.id] })),
    knowledgeItems: project.knowledgeItems.map((item) => ({ ...item, ...dictionary.knowledge[item.id] }))
  };
}

export function localizeSearchHit(hit: SearchHit, locale: Locale, projectId?: string): SearchHit {
  if (projectId !== "project-ai-landscape" || hit.sourceProjectId && hit.sourceProjectId !== projectId) return hit;
  const dictionary = dictionaries[locale];
  const copy = hit.kind === "topic" ? dictionary.topics[hit.id] : hit.kind === "keyIssue" ? dictionary.keyIssues[hit.id] : dictionary.knowledge[hit.id];
  if (!copy) return hit;
  return { ...hit, title: copy.title, ...(copy.description ?? copy.summary ?? copy.body ? { summary: copy.description ?? copy.summary ?? copy.body } : {}) };
}
